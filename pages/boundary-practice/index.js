function buildScenarios(expandedIndex = -1) {
  return SCENARIOS.map((scenario, index) => ({ ...scenario, expanded: index === expandedIndex }));
}

Page({
  data: {
    scenarios: buildScenarios(),
    companion: buildCompanion("elodie", "boundaryPractice", {
      image: getElodieVariantImage("think"),
      tag: "先看事实，再看边界",
      message: "这里没有标准答案。你可以先分清责任，再选择更适合当下安全感的回应。",
      size: "bust"
    })
  },

  toggleScenario(event) {
    const index = Number(event.currentTarget.dataset.index);
    const current = this.data.scenarios[index];
    this.setData({ scenarios: buildScenarios(current && current.expanded ? -1 : index) });
  }
});
